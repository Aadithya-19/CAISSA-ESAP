edge_detect.sv - GIVEN TO YOU. Do not edit this file.

This module is finished and correct. Your job this lesson is the testbench.

It watches a signal and emits a one-cycle pulse the moment that signal goes
from 0 to 1. It ignores the falling edge, and it ignores the signal just
sitting high.

  din      ___/‾‾‾‾‾‾‾‾‾\_________/‾‾‾‾‾‾‾
  rise     _____/‾\_________________/‾\____

We need this for `start` in lesson 03. A human holding a button down is high
for millions of clocks; the FSM wants to be kicked exactly once.

The trick is one register. Remember what din was last cycle, and a rising
edge is "high now, low then".

`rise` is registered rather than combinational, so it is stable for a whole
clock cycle. That is partly good practice and partly a favour to you: a
combinational pulse lives *between* edges, and a testbench that samples
after each edge would never see it.
*/

module edge_detect (
    input  logic clk,
    input  logic rst_n,     // ACTIVE LOW
    input  logic din,
    output logic rise       // one cycle pulse on the 0 -> 1 transition
);

    logic prev;

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            prev <= 1'b0;
            rise <= 1'b0;
        end else begin
            prev <= din;
            rise <= din & ~prev;
        end
    end

endmodule
